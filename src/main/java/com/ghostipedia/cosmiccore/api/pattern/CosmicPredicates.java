    private static PatternPredicate slrhTierBlock(Block requiredBlock) {
        return new PatternPredicate("SLRH Tier Block", worldState -> {
            var blockState = worldState.getBlockState();
            if (blockState.isAir() || blockState.is(requiredBlock)) {
                return null;
            }
            return new BlockMatchingError(worldState.getBlockPos(), List.of(requiredBlock));
        }, List.of(
                new BlockInfo(requiredBlock.defaultBlockState()),
                BlockInfo.EMPTY))
                .addTooltips(Component.translatable("cosmiccore.multiblock.pattern.slrh_tier_block"));
    }

    /**
     * Maps an SLRH casing block to its tier, or -1 if the block is not an SLRH tier casing.
     * Used by the controller to re-derive tier completeness from the formed structure.
     */
    public static int getSLRHTierForBlock(BlockState state) {
        if (state.is(CosmicBlocks.SUPERHEAVY_STEEL_CASING.get()) ||
                state.is(CosmicBlocks.BOLTED_HEAVY_FRAME_CASING.get()) ||
                state.is(CosmicBlocks.SOMARUST_CASING.get()) ||
                state.is(CosmicBlocks.SOUL_MUTED_CASING.get())) {
            return 0;
        }
        if (state.is(CosmicBlocks.BICHROMAL_NEVRAMITE_CASING.get())) {
            return 1;
        }
        if (state.is(CosmicBlocks.OSCILLATING_GILDED_PTHANTERUM_CASING.get()) ||
                state.is(CosmicBlocks.HIGHLY_FLEXIBLE_REINFORCED_TRINAVINE_CASING.get())) {
            return 2;
        }
        if (state.is(CosmicBlocks.ROYAL_ICHORIUM_CASING.get()) ||
                state.is(CosmicBlocks.MULTIPURPOSE_INTERSTELLAR_GRADE_CASING.get()) ||
                state.is(CosmicBlocks.ULTRA_POWERED_CASING.get())) {
            return 3;
        }
        return -1;
    }

    public static int validateSLRHTier(Set<Integer> tiersWithBlocks, Set<Integer> tiersWithAir) {
        if (tiersWithBlocks == null || tiersWithBlocks.isEmpty()) {
            return -1;
        }

        boolean t0HasBlocks = tiersWithBlocks.contains(0);
        boolean t0HasAir = tiersWithAir != null && tiersWithAir.contains(0);

        if (!t0HasBlocks || t0HasAir) {
            return -1;
        }

        int highestCompleteTier = 0;
        for (int tier = 1; tier <= 3; tier++) {
            boolean hasBlocks = tiersWithBlocks.contains(tier);
            boolean hasAir = tiersWithAir != null && tiersWithAir.contains(tier);

            if (hasBlocks && !hasAir && tier == highestCompleteTier + 1) {
                highestCompleteTier = tier;
            }
        }

        return highestCompleteTier;
    }

    public static int getSLRHPartialTierIndex(Set<Integer> tiersWithBlocks, Set<Integer> tiersWithAir) {
        if (tiersWithAir == null) {
            return 0;
        }

        boolean t0HasBlocks = tiersWithBlocks != null && tiersWithBlocks.contains(0);
        boolean t0HasAir = tiersWithAir.contains(0);
        if (t0HasAir) {
            return t0HasBlocks ? 0 : -1;
        }

        for (int tier = 1; tier <= 3; tier++) {
            boolean hasBlocks = tiersWithBlocks != null && tiersWithBlocks.contains(tier);
            boolean hasAir = tiersWithAir.contains(tier);
            if (hasBlocks && hasAir) {
                return tier;
            }
        }
        return 0;
    }

